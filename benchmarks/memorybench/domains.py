"""
Domain content packs for the synthetic corpus generator.

Each pack is a pool of *facts* — the things the labelling rule in
`corpus.py` says must be labelled — written as the short canonical
phrases that become ground-truth labels. `generate.py` samples from
these pools and renders each sampled fact into a message that contains
the phrase verbatim, which is what makes every generated label grounded
by construction.

The pools are deliberately written as domain vocabulary rather than as
whole sessions. Two sessions drawn from the same pack share the register
and the subject area but not the fact set, which is the realistic case:
two people working on Postgres migrations hit overlapping vocabulary and
different specifics.

Content note: these are engineering scenarios written for this
benchmark. They describe plausible work, not captured transcripts — the
`origin: synthetic` flag on every generated session says so, and the
runner reports the synthetic and real splits separately.
"""
